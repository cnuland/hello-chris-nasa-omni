#!/usr/bin/env bash
# Install the data and application tiers on this host as systemd (Quadlet) units, so the POC survives a reboot.
#
#   install-app.sh [--omni URL] [--decision URL] [--asr URL] [--chat URL] [--chat-model NAME]
#                  [--hostname NAME] [--no-tls]
#                  [--restore-db FILE.dump] [--restore-objects FILE.tgz]
#
# Defaults are the single-host (GB10) layout: every model server is a container on this host's `nasa` network,
# and one Gemma 4 server answers both perception and chat. Split layouts pass the other hosts' URLs.
#
# Idempotent: re-running updates the manifests and units and restarts the services. Credentials are generated
# once, on the first run, into podman's root secret store - never into a file, and never into this repo.
set -euo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
PODMAN="sudo podman"
# shellcheck source=lib.sh
. "$HERE/scripts/lib.sh"

OMNI=http://gemma4:8000 DECISION=http://dgemma-decision:8011 ASR=http://asr:8000
CHAT=http://gemma4:8000/v1 CHAT_MODEL=gemma4
HOSTNAME_CN="$(hostname -f 2>/dev/null || hostname)" TLS=1 DB_DUMP="" OBJECTS=""
while [ $# -gt 0 ]; do case "$1" in
  --omni) OMNI=$2; shift 2;; --decision) DECISION=$2; shift 2;; --asr) ASR=$2; shift 2;;
  --chat) CHAT=$2; shift 2;; --chat-model) CHAT_MODEL=$2; shift 2;;
  --hostname) HOSTNAME_CN=$2; shift 2;; --no-tls) TLS=0; shift;;
  --restore-db) DB_DUMP=$2; shift 2;; --restore-objects) OBJECTS=$2; shift 2;;
  *) die "unknown option $1";;
esac; done

command -v jq >/dev/null || die "jq is required (deploy/scripts/host-setup.sh installs it)"
[ -d /etc/containers/systemd ] || sudo install -d -m 0755 /etc/containers/systemd

# ------------------------------------------------------------------------------------------------ manifests
log "installing manifests and units"
sudo install -d -m 0755 /etc/nasa/kube /var/lib/nasa/models/perception
sudo install -m 0644 "$HERE"/kube/data.yaml "$HERE"/kube/app.yaml "$HERE"/kube/tls.yaml /etc/nasa/kube/
sudo install -m 0644 "$HERE"/quadlet/nasa.network "$HERE"/quadlet/nasa-media.volume \
                     "$HERE"/quadlet/nasa-data.kube "$HERE"/quadlet/nasa-app.kube \
                     "$HERE"/quadlet/perception.container /etc/containers/systemd/
if [ "$TLS" = 1 ]; then sudo install -m 0644 "$HERE"/quadlet/nasa-tls.kube /etc/containers/systemd/; fi
sudo install -m 0644 "$HERE"/quadlet/agent-dreaming.service "$HERE"/quadlet/agent-dreaming.timer /etc/systemd/system/

# ------------------------------------------------------------------------------------------------ configuration
# Model endpoints: the committed default with this host's overrides applied. Not a secret.
log "writing /etc/nasa/endpoints.yaml"
sudo tee /etc/nasa/endpoints.yaml >/dev/null <<YAML
# Generated by deploy/scripts/install-app.sh. Edit deploy/kube/endpoints.yaml and re-run to change the defaults.
apiVersion: v1
kind: ConfigMap
metadata: {name: nasa-endpoints}
data:
  AGENT_LLM_URL: "$CHAT"
  AGENT_LLM_MODEL: "$CHAT_MODEL"
  OMNI_URL: "$OMNI"
  DECISION_URL: "$DECISION"
  ASR_URL: "$ASR"
YAML
sudo chmod 0644 /etc/nasa/endpoints.yaml

# Earlier versions of this bundle staged a base64 Secret manifest and the config files on disk. They are now
# ConfigMaps inside the kube YAML and secrets in podman's store, so remove the leftovers rather than leaving a
# readable copy of the credentials behind.
sudo rm -rf /etc/nasa/secrets.yaml /etc/nasa/db-init /etc/nasa/tls-proxy.conf

nasa_secrets_ensure
if [ "$TLS" = 1 ]; then nasa_tls_ensure "$HOSTNAME_CN"; fi

# perception is a plain container unit, not a kube pod, so it is the one component that cannot read the kube
# Secret. Its environment file carries the same S3 credentials and is root-only.
log "writing /etc/nasa/perception.env"
sudo tee /etc/nasa/perception.env >/dev/null <<ENV
CAMERA_ID=cam-handheld
PERCEPTION_DEVICE=cuda
PERCEPTION_STRIDE_S=30
VIDEO_SOURCE=/media/sample.mp4
INVENTORY_API_URL=http://inventory-api:8080
OMNI_URL=$OMNI
OMNI_MODEL=gemma4
DECISION_URL=$DECISION
DECISION_MODEL=dgemma
DECISION_TIMEOUT_S=20
ASR_URL=$ASR
ASR_MODEL=asr
S3_ENDPOINT=http://rustfs:9000
S3_BUCKET=inventory
S3_ACCESS_KEY=$S3_ACCESS_KEY
S3_SECRET_KEY=$S3_SECRET_KEY
ENV
sudo chmod 0600 /etc/nasa/perception.env

# ------------------------------------------------------------------------------------------------ start
# Fail on a unit syntax error before systemd sees it. `if`, not `&&`: on the right of && set -e is
# suppressed, so a broken unit would sail through.
if [ -x /usr/libexec/podman/quadlet ]; then sudo /usr/libexec/podman/quadlet -dryrun >/dev/null; fi
sudo systemctl daemon-reload

log "data tier"
sudo systemctl start nasa-data.service
nasa_wait_db 300

if [ -n "$DB_DUMP" ]; then
  log "restoring the database from $DB_DUMP"
  # --no-owner restores everything as postgres; the ALTER loop below hands it back to the application role.
  $PODMAN exec -i inventory-db-postgres pg_restore -U postgres -d inventory --clean --if-exists --no-owner < "$DB_DUMP" || true
  nasa_db_reown
fi
if [ -n "$OBJECTS" ]; then
  log "restoring the object store from $OBJECTS"
  # Into the named volume through a throwaway container, then hand it to the uid the RustFS image runs as.
  $PODMAN run --rm -i --user 0 -v nasa-objects:/data docker.io/library/busybox:stable \
    sh -c 'tar -xzf - -C /data && chown -R 10001:10001 /data' < "$OBJECTS"
fi

log "application tier"
sudo systemctl start nasa-app.service
nasa_wait_api 300
nasa_bucket_ensure

if [ "$TLS" = 1 ]; then
  log "TLS front door"
  sudo systemctl start nasa-tls.service
fi
sudo systemctl enable --now agent-dreaming.timer >/dev/null 2>&1 || true

log "installed"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
if [ "$TLS" = 1 ]; then
  echo "    dashboard: https://${IP:-$HOSTNAME_CN}/   (self-signed unless you replaced the nasa-tls secret)"
else
  echo "    dashboard: http://127.0.0.1:8080/   (loopback only; --no-tls published no public port)"
fi
echo "    perception is installed but not started: attach a feed, then 'sudo systemctl start perception'"
